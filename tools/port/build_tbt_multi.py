"""One turn-by-turn package (g70.tbt) for several firmwares, the way build_multi.sh makes the
bridge: the single-firmware tbt installer of the first set, with each set's checksums and deltas
under firmware/<name>/ (sums.sh + *.lpd). The installer uses the set whose stock files the unit has
(pick_firmware), whatever the firmware is called.
usage: build_tbt_multi.py <out dir> <package name> <name>=<release-<port>-tbt dir> ...
       (run in the leafia container; <out dir> must not exist)"""
import os, re, shutil, subprocess, sys

out, title = sys.argv[1], sys.argv[2]
sets = [a.split('=', 1) for a in sys.argv[3:]]
assert not os.path.exists(out), out + ' exists'
pkg = os.path.join(out, 'pkg')
shutil.copytree(os.path.join(sets[0][1], 'pkg'), pkg)
for f in os.listdir(os.path.join(pkg, 'files')):
    assert f.endswith('.lpd'), f
    os.remove(os.path.join(pkg, 'files', f))
os.rmdir(os.path.join(pkg, 'files'))

VAL = re.compile(r'^((?:PRODUCT|SUM_STOCK_\w+|SUM_NEW_\w+|SUM_PREV_\w+))=(.*)$')
for name, rel in sets:
    c = os.path.join(rel, 'pkg', 'scripts', 'common.sh')
    vals = [(m.group(1), m.group(2)) for m in (VAL.match(l.rstrip('\n')) for l in open(c)) if m]
    d = os.path.join(pkg, 'firmware', name)
    os.makedirs(d)
    with open(os.path.join(d, 'sums.sh'), 'w', newline='\n') as f:
        f.write('# firmware set %s: generated by ports/build_tbt_multi.py\n' % name)
        f.write(''.join('%s=%s\n' % kv for kv in vals))
    src = os.path.join(rel, 'pkg', 'files')
    for f in sorted(os.listdir(src)):
        shutil.copy(os.path.join(src, f), d)

p = os.path.join(pkg, 'scripts', 'common.sh')
s = open(p).read()
# the per-firmware values move to firmware/<name>/sums.sh
s = re.sub(r'^(?:PRODUCT|SUM_(?:STOCK|NEW|PREV)_\w+|AA_LPD)=.*\n', '', s, flags=re.M)
assert 'SUM_STOCK_HKMC_DiPO_apk=' not in s and 'AA_LPD=files' not in s
n = s.count('files/$_n.lpd')
assert n == 3, n
s = s.replace('files/$_n.lpd', '$FW_DIR/$_n.lpd')
# header
i = s.index('# g70.tbt - '); j = s.index('#\n#   HKMC_DiPO')
s = s.replace('(stock-gated to stepofspec >= 999, this car is 95)', '(stock-gated to stepofspec >= 999)')
s = s[:i] + ('# g70.tbt - turn-by-turn on the cluster and HUD for wired Android Auto and CarPlay (and USB\n'
             '# wireless adapters): %s. One firmware set per supported build in firmware/<name>/\n'
             '# (sums.sh + deltas); the set whose stock files this unit has is used (pick_firmware at the end).\n'
             '# The turn-by-turn part of the G70 bridge (g70.carplay.bt) without its wireless parts.\n') % title + s[j:]
s = s.replace('(files/<app>.lpd deltas,', '(firmware/<name>/<app>.lpd deltas,')
old = '''check_unit() {
    local _p _n
    _p=$(getprop ro.build.product 2>/dev/null)
'''
assert s.count(old) == 1
s = s.replace(old, old + '''    if [ -z "$FW_SET" ]; then
        log "firmware '$_p': this unit's files match none of this package's firmware sets ($(fw_sets))"
        log "FAIL: no firmware set for this unit"
        return 1
    fi
    log "firmware set $FW_SET (built on $PRODUCT)"
''')
old = '''        log "FAIL: libautoreceiver_infobank.so is neither stock nor this build"
        return 1
    fi
    return 0
}'''
assert s.count(old) == 1
s = s.replace(old, old[:-len('    return 0\n}')] + '''    mkdir -p "$BACKUP_DIR" && echo "$FW_SET" > "$BACKUP_DIR/firmware-set" || return 1
    return 0
}''')
s = s.rstrip('\n') + '''

# ---- firmware sets ----
# firmware/<name>/sums.sh holds one firmware's values (PRODUCT, SUM_STOCK_*, SUM_NEW_*, SUM_PREV_*)
# and its deltas sit beside it. The set whose files this unit has (each app and the Android Auto
# library stock, ours or an earlier build of ours) is used. Uninstall after a firmware update,
# when no set matches any more, falls back to the set recorded at install; the restore steps
# still leave alone any file that is not this package's.
FW_SET=""; FW_DIR=""; AA_LPD=""
fw_sets() { local _d _o=""; for _d in firmware/*/sums.sh; do _d=${_d%/sums.sh}; _o="$_o ${_d#firmware/}"; done; echo "${_o# }"; }
fw_load() { . "./firmware/$1/sums.sh"; FW_DIR=firmware/$1; AA_LPD=$FW_DIR/libautoreceiver_infobank.tbt.lpd; }
fw_matches() {
    local _n
    for _n in $APPS; do
        is_stock_app "$_n" || is_our_app "$_n" || is_prev_app "$_n" || return 1
    done
    sum_eq "$AA_LIB" "$SUM_STOCK_AALIB" || sum_eq "$AA_LIB" "$SUM_NEW_AALIB" || is_prev_aalib
}
pick_firmware() {
    local _s _rec=""
    for _s in $(fw_sets); do
        fw_load "$_s"
        if fw_matches; then FW_SET=$_s; return 0; fi
    done
    [ -r "$BACKUP_DIR/firmware-set" ] && read -r _rec < "$BACKUP_DIR/firmware-set"
    if [ -n "$_rec" ] && [ -r "firmware/$_rec/sums.sh" ]; then
        fw_load "$_rec"; FW_SET=$_rec; return 0
    fi
    return 1
}
pick_firmware || true
'''
open(p, 'w', newline='\n').write(s)

nd = os.path.join(pkg, 'NEMESIS.data')
t = open(nd).read()
t = re.sub(r'^name=.*$', 'name=' + title, t, flags=re.M)
open(nd, 'w', newline='\n').write(t)
for f in os.listdir(os.path.join(pkg, 'scripts')) + ['../bin/status.sh']:
    subprocess.check_call(['mksh', '-n', os.path.join(pkg, 'scripts', f)])
os.makedirs(os.path.join(out, 'dist', 'packages'))
subprocess.check_call(['zip', '-qrX', '../dist/packages/g70.tbt.zip', '.'], cwd=pkg)
print(subprocess.check_output(['md5sum', os.path.join(out, 'dist', 'packages', 'g70.tbt.zip')]).decode().strip())

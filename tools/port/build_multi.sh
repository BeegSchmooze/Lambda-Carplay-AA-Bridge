#!/bin/sh
# One bridge package (g70.carplay.bt) for several firmwares: the update 22 scripts with one
# firmware set per supported build under firmware/<name>/ (sums.sh = the stock files that build
# was made from, our builds and earlier builds an install may replace; *.lpd = its deltas).
# The installer uses the set whose files the unit has (scripts/common.sh pick_firmware).
# Sets come from release-<port>/pkg (ports/build_full_port.sh), without camera alerts.
# -> release-multi/pkg, release-multi/dist/packages/g70.carplay.bt.zip
# usage: build_multi.sh  (run in the leafia container)
set -e
W=/work
R=$W/release-multi
rm -rf $R && mkdir -p $R
cp -r $W/release-u22/pkg $R/pkg
rm -f $R/pkg/files/*.lpd
C=$R/pkg/scripts/common.sh
# name:port dir:earlier builds of this package on that firmware, ','-separated (a package dir with
# scripts/common.sh, or a firmware set's sums.sh): their SUM_NEW_* and SUM_PREV_* become SUM_PREV_*
P=$W/prev
SETS="251120:g70-251120-nocam:$W/release-u22/pkg,$P/v12/firmware/251120/sums.sh,$P/v13/firmware/251120/sums.sh,$P/u24/firmware/251120/sums.sh
250818:g70-250818-nocam:$W/release-g70-250818/pkg,$P/v12/firmware/250818/sums.sh,$P/v13/firmware/250818/sums.sh,$P/u24/firmware/250818/sums.sh
260507:g70-260507-nocam:$W/release-g70-260507/pkg,$P/v12/firmware/260507/sums.sh,$P/u23test1,$P/v13/firmware/260507/sums.sh,$P/u24/firmware/260507/sums.sh"
echo "$SETS" | while IFS=: read -r name port prev; do
    P=$W/release-$port/pkg
    D=$R/pkg/firmware/$name
    mkdir -p $D
    cp $P/files/*.lpd $D/
    python3 - "$P/scripts/common.sh" "$prev" "$D/sums.sh" "$name" <<'EOF'
import os, re, sys
cur, prevs, out, name = sys.argv[1:5]
def vals(p):
    d = {}
    for l in open(p):
        m = re.match(r'^((?:PRODUCT|SUM_STOCK_\w+|SUM_NEW_\w+|SUM_PREV_\w+))=(.*)$', l.rstrip('\n'))
        if m: d[m.group(1)] = m.group(2).strip('"')
    return d
c = vals(cur)
ps = []
for p in prevs.split(','):
    f = p if p.endswith('.sh') and not os.path.isdir(p) else os.path.join(p, 'scripts', 'common.sh')
    pv = vals(f)
    assert all(pv.get(k) == v for k, v in c.items() if k.startswith('SUM_STOCK_')), 'earlier build not made on the same stock files: ' + p
    ps.append(pv)
lines = ['# firmware set %s: generated by ports/build_multi.sh' % name, 'PRODUCT=' + c['PRODUCT']]
lines += ['%s=%s' % (k, v) for k, v in c.items() if k.startswith('SUM_STOCK_')]
lines += ['%s=%s' % (k, v) for k, v in c.items() if k.startswith('SUM_NEW_')]
for k, v in c.items():
    if not k.startswith('SUM_NEW_'): continue
    kp = k.replace('SUM_NEW_', 'SUM_PREV_')
    pv = c.get(kp, '').split()
    for p in ps:
        pv += p.get(kp, '').split() + [p.get(k, '')]
    pv = [x for x in pv if x and x != v]
    lines.append('%s="%s"' % (kp, ' '.join(dict.fromkeys(pv))))
open(out, 'w').write('\n'.join(lines) + '\n')
EOF
done
python3 - $C <<'EOF'
import re, sys
p = sys.argv[1]
s = open(p).read()
# the per-firmware values move to firmware/<name>/sums.sh
s = re.sub(r'^PRODUCT=.*\n', '', s, flags=re.M)
s = re.sub(r'^# stock files the builds were made from\n', '', s, flags=re.M)
s = re.sub(r'^# our builds \(stock APK \+ patched classes\.dex\)\n', '', s, flags=re.M)
s = re.sub(r'^# earlier builds of this package an install may replace \(the stock backup is kept\)\n', '', s, flags=re.M)
s = re.sub(r'^# earlier builds of the library this package may replace \(rebuilt from the stock backup\)\n', '', s, flags=re.M)
s = re.sub(r'^SUM_(STOCK|NEW|PREV)_\w+=.*\n', '', s, flags=re.M)
s = re.sub(r'^AA_LPD=.*\n', '', s, flags=re.M)
assert 'SUM_STOCK_HKMC_DiPO_apk=' not in s
s = s.replace('"files/$_n.lpd"', '"$FW_DIR/$_n.lpd"').replace('payload files/$_n.lpd missing', 'payload $FW_DIR/$_n.lpd missing')
assert s.count('"$FW_DIR/$_n.lpd"') == 2
# header: one package for several firmwares, no camera alerts (a separate add-on)
old = '''# g70.carplay.bt - wireless CarPlay for the Genesis G70 (built on IKFL.USA 251120; any
# firmware whose stock files match byte for byte),'''
assert s.count(old) == 1
s = s.replace(old, '''# g70.carplay.bt - wireless CarPlay / Android Auto for the Genesis G70. One firmware set per
# supported build in firmware/<name>/ (sums.sh + deltas); the set whose stock files this unit
# has is used (pick_firmware at the end), whatever the firmware is called,''')
old = '''#   cameras        speed / red-light camera alerts on the HUD from the owner's list
#                    (/data/leafia/cameras.csv, none shipped): GPM matches GPS against it
#                    (sys.leafia.cam), the car navigation shows it in its trap frames
'''
assert s.count(old) == 1
s = s.replace(old, '')
s = s.replace('(files/libautoreceiver_infobank.tbt.lpd, hash-gated delta)', '(firmware/<name>/libautoreceiver_infobank.tbt.lpd, hash-gated delta)')
s = s.replace('own stock files (files/<app>.lpd deltas,', 'own stock files (firmware/<name>/<app>.lpd deltas,')
old = '''check_unit() {
    local _p _n
    _p=$(getprop ro.build.product 2>/dev/null)'''
new = '''check_unit() {
    local _p _n
    _p=$(getprop ro.build.product 2>/dev/null)
    if [ -z "$FW_SET" ]; then
        log "firmware '$_p': this unit's files match none of this package's firmware sets ($(fw_sets))"
        log "FAIL: no firmware set for this unit"
        return 1
    fi
    log "firmware set $FW_SET (built on $PRODUCT)"'''
assert s.count(old) == 1
s = s.replace(old, new)
old = '''        log "libautoreceiver_infobank.so: earlier build of this package - will be replaced (stock backup present)"
    else
        log "live libautoreceiver_infobank.so md5=$(file_md5 $AA_LIB)"
        log "FAIL: libautoreceiver_infobank.so is neither stock nor this build"
        return 1
    fi
    return 0
}'''
assert s.count(old) == 1
s = s.replace(old, old[:-len('    return 0\n}')] + '''    mkdir -p "$BACKUP_DIR" && echo "$FW_SET" > "$BACKUP_DIR/firmware-set" || return 1
    return 0
}''')
s = s.rstrip('\n') + '''

# ---- firmware sets ----
# firmware/<name>/sums.sh holds one firmware's values (PRODUCT, SUM_STOCK_*, SUM_NEW_*, SUM_PREV_*)
# and its deltas sit beside it. The set whose files this unit has (each app and the Android Auto
# library stock, ours or an earlier build of ours) is used. Uninstall after a firmware update,
# when no set matches any more, falls back to the set recorded at install; the restore steps
# still leave alone any file that is not this package's.
FW_SET=""; FW_DIR=""; AA_LPD=""
fw_sets() { local _d _o=""; for _d in firmware/*/sums.sh; do _d=${_d%/sums.sh}; _o="$_o ${_d#firmware/}"; done; echo "${_o# }"; }
fw_load() { . "./firmware/$1/sums.sh"; FW_DIR=firmware/$1; AA_LPD=$FW_DIR/libautoreceiver_infobank.tbt.lpd; }
fw_matches() {
    local _n
    for _n in $APPS; do
        is_stock_app "$_n" || is_our_app "$_n" || is_prev_app "$_n" || return 1
    done
    sum_eq "$AA_LIB" "$SUM_STOCK_AALIB" || sum_eq "$AA_LIB" "$SUM_NEW_AALIB" || is_prev_aalib
}
pick_firmware() {
    local _s _rec=""
    for _s in $(fw_sets); do
        fw_load "$_s"
        if fw_matches; then FW_SET=$_s; return 0; fi
    done
    [ -r "$BACKUP_DIR/firmware-set" ] && read -r _rec < "$BACKUP_DIR/firmware-set"
    if [ -n "$_rec" ] && [ -r "firmware/$_rec/sums.sh" ]; then
        fw_load "$_rec"; FW_SET=$_rec; return 0
    fi
    return 1
}
pick_firmware || true
'''
open(p, 'w').write(s)
EOF
sed -i 's/^name=.*/name=G70 Wireless CarPlay \/ Android Auto bridge (251120, 250818, 260507)/' $R/pkg/NEMESIS.data
# store-format descriptor (1.1: version, description, os/models, conflicts); bump its version there
python3 $W/ports/store_descriptor.py $R/pkg bridge > /dev/null
for f in $R/pkg/scripts/*.sh $R/pkg/bin/*.sh; do mksh -n "$f"; done
for d in $R/pkg/firmware/*; do echo "== ${d##*/}"; cat $d/sums.sh | cut -c1-90; ls $d; done
mkdir -p $R/dist/packages
(cd $R/pkg && zip -qrX ../dist/packages/g70.carplay.bt.zip .)
md5sum $R/dist/packages/g70.carplay.bt.zip
